CREATE TABLE app_user (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  display_name VARCHAR(100) NOT NULL,
  email VARCHAR(254) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  role VARCHAR(20) NOT NULL CHECK (role IN ('USER', 'MANAGER', 'ADMIN')),
  enabled BOOLEAN NOT NULL DEFAULT TRUE,
  token_version BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL,
  CONSTRAINT ck_user_email_normalized CHECK (email = lower(trim(email)))
);
CREATE TABLE equipment_category (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(80) NOT NULL UNIQUE,
  description VARCHAR(500),
  active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE storage_location (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(30) NOT NULL UNIQUE,
  name VARCHAR(100) NOT NULL,
  building VARCHAR(100) NOT NULL,
  room VARCHAR(30) NOT NULL,
  active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE equipment_item (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  inventory_code VARCHAR(40) NOT NULL UNIQUE,
  name VARCHAR(120) NOT NULL,
  description VARCHAR(2000),
  category_id BIGINT NOT NULL REFERENCES equipment_category(id),
  location_id BIGINT NOT NULL REFERENCES storage_location(id),
  lifecycle VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (lifecycle IN ('ACTIVE', 'RETIRED')),
  version BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE reservation (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  requester_id BIGINT NOT NULL REFERENCES app_user(id),
  equipment_id BIGINT NOT NULL REFERENCES equipment_item(id),
  starts_at TIMESTAMPTZ NOT NULL,
  ends_at TIMESTAMPTZ NOT NULL,
  purpose VARCHAR(500) NOT NULL,
  status VARCHAR(20) NOT NULL CHECK (status IN ('REQUESTED','APPROVED','REJECTED','CANCELLED','EXPIRED','COMPLETED')),
  decided_by BIGINT REFERENCES app_user(id),
  decided_at TIMESTAMPTZ,
  decision_reason VARCHAR(500),
  version BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL,
  CHECK (starts_at < ends_at),
  CHECK ((decided_by IS NULL) = (decided_at IS NULL)),
  CHECK (status <> 'REJECTED' OR (decision_reason IS NOT NULL AND length(trim(decision_reason)) > 0))
);
CREATE INDEX idx_reservation_equipment_period ON reservation(equipment_id, status, starts_at, ends_at);
CREATE INDEX idx_reservation_requester ON reservation(requester_id, created_at DESC);
CREATE TABLE loan (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reservation_id BIGINT NOT NULL UNIQUE REFERENCES reservation(id),
  equipment_id BIGINT NOT NULL REFERENCES equipment_item(id),
  issued_by BIGINT NOT NULL REFERENCES app_user(id),
  issued_at TIMESTAMPTZ NOT NULL,
  due_at TIMESTAMPTZ NOT NULL,
  returned_by BIGINT REFERENCES app_user(id),
  returned_at TIMESTAMPTZ,
  issue_condition VARCHAR(20) NOT NULL CHECK (issue_condition IN ('GOOD','WORN')),
  return_condition VARCHAR(20) CHECK (return_condition IN ('GOOD','WORN','DAMAGED')),
  return_note VARCHAR(1000),
  CHECK (issued_at < due_at),
  CHECK (returned_at IS NULL OR returned_at >= issued_at),
  CHECK ((returned_at IS NULL AND returned_by IS NULL AND return_condition IS NULL)
      OR (returned_at IS NOT NULL AND returned_by IS NOT NULL AND return_condition IS NOT NULL))
);
CREATE UNIQUE INDEX uk_loan_open_equipment ON loan(equipment_id) WHERE returned_at IS NULL;
CREATE TABLE maintenance_period (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  equipment_id BIGINT NOT NULL REFERENCES equipment_item(id),
  created_by BIGINT NOT NULL REFERENCES app_user(id),
  starts_at TIMESTAMPTZ NOT NULL,
  ends_at TIMESTAMPTZ NOT NULL,
  reason VARCHAR(500) NOT NULL,
  status VARCHAR(20) NOT NULL CHECK (status IN ('OPEN','CLOSED','CANCELLED')),
  closed_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL,
  CHECK (starts_at < ends_at),
  CHECK ((status = 'CLOSED') = (closed_at IS NOT NULL))
);
CREATE INDEX idx_maintenance_equipment_period ON maintenance_period(equipment_id, status, starts_at, ends_at);
CREATE TABLE audit_event (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id BIGINT REFERENCES app_user(id),
  equipment_id BIGINT REFERENCES equipment_item(id),
  reservation_id BIGINT REFERENCES reservation(id),
  event_type VARCHAR(40) NOT NULL,
  from_state VARCHAR(30),
  to_state VARCHAR(30),
  note VARCHAR(1000),
  occurred_at TIMESTAMPTZ NOT NULL,
  CHECK (equipment_id IS NOT NULL OR reservation_id IS NOT NULL)
);
CREATE INDEX idx_audit_reservation_time ON audit_event(reservation_id, occurred_at, id);
CREATE INDEX idx_equipment_category_location ON equipment_item(category_id, location_id);
